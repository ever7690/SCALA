function check(name, callback) { callback(); checks.push(name); }
function finish(save, correct = 12) {
  for (let index = 0; index < 12; index++) {
    answerQuestion(save, index < correct ? currentQuestion(save).answer : 1);
    advanceSession(save);
  }
  return save.session;
}
const normalized = value => value.normalize('NFKD').replace(/[\u0300-\u036f]/g, '').toLowerCase().replace(/[^a-z0-9]/g, '');
check('240 preguntas propias, cuatro opciones únicas y pasajes con evidencia', () => {
  assert.equal(heroes.length, 12);
  assert.equal(questions.length, 240);
  assert.equal(new Set(questions.map(item => item.id)).size, 240);
  assert.equal(new Set(questions.map(item => item.prompt)).size, 240);
  for (const item of heroes) assert.equal(questions.filter(question => question.heroId === item.id).length, 20);
  for (const question of questions) {
    assert.equal(question.choices.length, 4);
    assert.equal(new Set(question.choices.map(normalized)).size, 4);
    assert.ok(question.answer >= 0 && question.answer < 4);
    assert.ok(question.reference.length > 5 && question.verseKeys.length > 0 && question.explanation.length > 25);
    for (const term of question.evidence) assert.ok(normalized(question.verse).includes(normalized(term)), question.id + ': ' + term);
  }
  const report = JSON.parse(fs.readFileSync('docs/fuentes-preguntas.json'));
  assert.equal(report.questionsSHA256, crypto.createHash('sha256').update(fs.readFileSync('src/data/questions.json')).digest('hex'));
});
