check('Ayudas atómicas, dos opciones incorrectas y reloj congelado', () => {
  const save = freshSave();
  startSession(save, 'journey', 'noe', 13);
  assert.deepEqual(aidCosts, { half: 25, verse: 20, pause: 30 });
  assert.ok(useAid(save, 'half').applied);
  assert.equal(save.coins, 95);
  assert.equal(save.session.removedChoices.length, 2);
  assert.ok(!save.session.removedChoices.includes(currentQuestion(save).answer));
  assert.equal(useAid(save, 'half').applied, false);
  assert.equal(answerQuestion(save, save.session.removedChoices[0]), null);
  assert.ok(useAid(save, 'verse').applied);
  assert.equal(save.coins, 75);
  assert.ok(useAid(save, 'pause').applied);
  assert.equal(save.coins, 45);
  for (let index = 0; index < 6; index++) tickSession(save, 2000);
  assert.equal(save.session.elapsedMs, 0);
  assert.equal(save.session.frozenMsLeft, 0);
  tickSession(save, 1000);
  assert.equal(save.session.elapsedMs, 1000);
  assert.equal(useAid(save, 'pause').applied, false);
  const resumed = restoreSave(JSON.parse(JSON.stringify(save)));
  assert.deepEqual(resumed.session.removedChoices, save.session.removedChoices);
  assert.equal(resumed.session.halfUsed, true);
  assert.equal(resumed.session.verseUsed, true);
  assert.equal(resumed.coins, 45);
  answerQuestion(resumed, 0);
  advanceSession(resumed);
  assert.equal(resumed.session.halfUsed, false);
  assert.equal(resumed.session.verseUsed, false);
  assert.equal(resumed.session.freezeUsed, true);
  resumed.coins = 19;
  assert.equal(useAid(resumed, 'verse').applied, false);
  assert.equal(resumed.coins, 19);
});
