check('Duelo persistente con igualdad de preguntas, opciones y reglas', () => {
  const save = freshSave();
  assert.ok(startDuel(save, ['Ana', 'Luis'], 'noe', 40));
  const ids = [...save.session.questionIds];
  const orders = [...save.session.choiceOrders];
  assert.equal(useAid(save, 'half').applied, false);
  tickSession(save, 1200);
  finish(save, 10);
  assert.equal(save.duel.stage, 1);
  settleSession(save);
  assert.equal(save.duel.stage, 1);
  const resumed = restoreSave(JSON.parse(JSON.stringify(save)));
  assert.ok(secondDuelTurn(resumed));
  assert.equal(secondDuelTurn(resumed), false);
  assert.deepEqual(resumed.session.questionIds, ids);
  assert.deepEqual(resumed.session.choiceOrders, orders);
  tickSession(resumed, 1500);
  finish(resumed, 11);
  assert.equal(resumed.duel.stage, 2);
  assert.equal(duelWinner(resumed.duel), 1);
  assert.equal(resumed.xp, 0);
  assert.equal(resumed.coins, 120);
  assert.equal(resumed.rounds, 0);
  assert.equal(resumed.history.length, 0);
  assert.equal(secondDuelTurn(resumed), false);
  resumed.duel.results[0].correct = 11;
  resumed.duel.results[0].elapsedMs = resumed.duel.results[1].elapsedMs;
  assert.equal(duelWinner(resumed.duel), -1);
  resumed.duel.results[0].elapsedMs += 1000;
  assert.equal(duelWinner(resumed.duel), 1);
});
